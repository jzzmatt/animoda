import { describe, expect, it } from "vitest";
import OpenAI from "openai";
import {
  conceptPrompt,
  createOpenAiFashionProvider,
  defaultOpenAiImageModel,
  resetOpenAiModelVerificationForTests,
  tryOnPrompt,
  type ImageClient,
} from "./fashion-image-provider";
import type { ConceptBrief, TryOnBrief } from "./fashion-image-provider";

const secret = "sk-test-secret-value";

function jpeg(marker: number): Buffer {
  const bytes = Buffer.alloc(64, marker);
  bytes[0] = 0xff;
  bytes[1] = 0xd8;
  bytes[2] = 0xff;
  return bytes;
}

function client(handlers: Partial<ImageClient["images"]> & { retrieve?: ImageClient["models"]["retrieve"] }): ImageClient {
  return {
    models: { retrieve: handlers.retrieve ?? (async () => ({ id: defaultOpenAiImageModel })) },
    images: {
      generate: handlers.generate ?? (async () => ({ created: 0, data: [{ b64_json: jpeg(1).toString("base64") }] })),
      edit: handlers.edit ?? (async () => ({ created: 0, data: [{ b64_json: jpeg(2).toString("base64") }] })),
    },
  };
}

const conceptBrief: ConceptBrief = {
  animalName: "Plains zebra",
  scientificName: "Equus quagga",
  characteristics: "High-contrast stripes.",
  colors: "Black, white",
  garmentTitle: "Avant-garde trench",
  garmentDescription: "An asymmetric drape.",
  textile: "Technical gabardine",
  occasion: "Casual & Street",
  wearer: "adult",
  audience: "Women",
  reference: null,
};

describe("OpenAI fashion image provider", () => {
  it("builds prompts that treat the animal as a reference and keep children's clothing age-appropriate", () => {
    const adult = conceptPrompt(conceptBrief);
    expect(adult).toMatch(/creative reference/i);
    expect(adult).toMatch(/Do not depict the living animal/);
    const child = conceptPrompt({ ...conceptBrief, wearer: "child", audience: "Girls" });
    expect(child).toMatch(/age-appropriate children's outfit/);
    expect(child).not.toMatch(/99\.4|guaranteed fit/i);
    expect(tryOnPrompt({
      portrait: { bytes: jpeg(3), mediaType: "image/jpeg", filename: "portrait.jpg" },
      garment: { bytes: jpeg(4), mediaType: "image/jpeg", filename: "garment.jpg" },
      garmentTitle: "Kids heritage capsule",
      textile: "Organic cotton knit",
      wearer: "child",
    })).toMatch(/Preserve the person's identity/);
  });

  it("calls the documented Sunburst model and returns the generated bytes", async () => {
    resetOpenAiModelVerificationForTests();
    const generateCalls: OpenAI.ImageGenerateParamsNonStreaming[] = [];
    const provider = createOpenAiFashionProvider({
      apiKey: secret,
      client: client({
        generate: async (body) => {
          generateCalls.push(body);
          return { created: 0, data: [{ b64_json: jpeg(9).toString("base64") }] };
        },
      }),
    });
    const image = await provider.generateConcept(conceptBrief);
    expect(image.mediaType).toBe("image/jpeg");
    expect(image.bytes[0]).toBe(0xff);
    expect(generateCalls[0]?.model).toBe(defaultOpenAiImageModel);
    expect(generateCalls[0]).not.toHaveProperty("response_format");
    expect(generateCalls[0]).not.toHaveProperty("input_fidelity");
    expect(JSON.stringify(generateCalls)).not.toContain(secret);
  });

  it("discards an unchanged try-on and maps rate limits without leaking the key", async () => {
    resetOpenAiModelVerificationForTests();
    const portrait = jpeg(5);
    const garment = jpeg(6);
    const brief: TryOnBrief = {
      portrait: { bytes: portrait, mediaType: "image/jpeg", filename: "portrait.jpg" },
      garment: { bytes: garment, mediaType: "image/jpeg", filename: "garment.jpg" },
      garmentTitle: "Elegant high-slit gown",
      textile: "Silk charmeuse",
      wearer: "adult",
    };
    const unchanged = createOpenAiFashionProvider({
      apiKey: secret,
      client: client({
        edit: async () => ({ created: 0, data: [{ b64_json: portrait.toString("base64") }] }),
      }),
    });
    await expect(unchanged.editTryOn(brief)).rejects.toThrow(/unchanged input image/);

    resetOpenAiModelVerificationForTests();
    const limited = createOpenAiFashionProvider({
      apiKey: secret,
      client: client({
        edit: async () => {
          throw new OpenAI.APIError(429, { message: `slow down ${secret}`, code: "rate_limit_exceeded" }, "slow down", new Headers());
        },
      }),
    });
    await expect(limited.editTryOn(brief)).rejects.toThrow(/rate-limited/);
    await expect(limited.editTryOn(brief)).rejects.not.toThrow(/sk-test-secret-value/);
  });

  it("reports a missing model without generating an image", async () => {
    resetOpenAiModelVerificationForTests();
    let generated = false;
    const provider = createOpenAiFashionProvider({
      apiKey: secret,
      model: "gpt-image-2.5-sunburst",
      client: client({
        retrieve: async () => {
          throw new OpenAI.APIError(404, { message: "no such model", code: "model_not_found" }, "missing", new Headers());
        },
        generate: async () => {
          generated = true;
          return { created: 0, data: [] };
        },
      }),
    });
    await expect(provider.generateConcept(conceptBrief)).rejects.toThrow(/not available to this OpenAI account/);
    expect(generated).toBe(false);
  });
});
